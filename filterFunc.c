// Histórico das últimas 41 amostras
double fir_history[FIR_TAP_NUM] = {0.0};
unsigned int fir_index = 0;

// Executar uma vez por cada nova amostra do ADC
double fir_filter(double input)
{
    fir_history[fir_index] = input;

    double output = 0.0;
    unsigned int index = fir_index;

    for (unsigned int i = 0; i < FIR_TAP_NUM; i++)
    {
        output += fir_coefficients[i] * fir_history[index];

        if (index == 0)
            index = FIR_TAP_NUM - 1;
        else
            index--;
    }

    fir_index++;

    if (fir_index >= FIR_TAP_NUM)
        fir_index = 0;

    return output;
}